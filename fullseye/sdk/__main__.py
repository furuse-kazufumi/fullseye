"""``python -m fullseye.sdk`` discovery CLI / SDK 検出用 CLI。"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import sysconfig
import tempfile

from . import abi_version, package_root, payload_paths


def _bracket(value: str) -> str:
    """Quote a CMake value without treating backslashes as escapes / CMake 用の安全な引用。"""
    if "]==]" in value:
        raise ValueError("SDK path contains an unsupported CMake delimiter")
    return "[==[%s]==]" % value


def _cmake_dir() -> Path:
    """Write an environment-specific Config shim and return its directory.

    The immutable wheel config needs the Python that selected it. A small
    per-interpreter shim records it outside site-packages, so concurrent venvs
    cannot overwrite each other. / 不変の wheel Config に、その Config を選んだ
    Python を渡すため、site-packages 外の interpreter ごとの小さな shim を作る。
    """
    config = Path(__file__).resolve().parent / "cmake" / "fullseyeConfig.cmake"
    source, include = payload_paths()
    if not config.is_file() or not source.is_file() or not include.is_dir():
        raise RuntimeError("Fullseye SDK payload is incomplete; reinstall fullseye")
    key = hashlib.sha256(str(Path(sys.executable).resolve()).encode("utf-8")).hexdigest()[:16]
    directory = Path(tempfile.gettempdir()) / "fullseye-sdk" / key
    directory.mkdir(parents=True, exist_ok=True)
    shim = directory / "fullseyeConfig.cmake"
    text = "\n".join((
        "# Generated by python -m fullseye.sdk; do not edit.",
        "set(fullseye_PYTHON_EXECUTABLE %s)" % _bracket(str(Path(sys.executable).resolve())),
        "set(fullseye_PYTHON_RUNTIME_ROOT %s)" % _bracket(str(package_root().parent)),
        "set(fullseye_PYTHON_HOME %s)" % _bracket(str(Path(sys.prefix).resolve())),
        "set(fullseye_SDK_ABI_VERSION %s)" % _bracket(abi_version()),
        "set(fullseye_SDK_SOURCE_FILE %s)" % _bracket(str(source.resolve())),
        "set(fullseye_SDK_INCLUDE_DIR %s)" % _bracket(str(include.resolve())),
        "include(%s)" % _bracket(str(config.resolve())),
        "",
    ))
    if not shim.is_file() or shim.read_text(encoding="utf-8") != text:
        shim.write_text(text, encoding="utf-8", newline="\n")
    return directory


def _platform_commands(component: str) -> dict[str, str]:
    """Return directly usable prerequisite commands / OS 別の導入コマンドを返す。"""
    commands = {
        "cmake": {
            "Windows": "winget install Kitware.CMake",
            "Linux": "sudo apt-get install cmake",
            "macOS": "brew install cmake",
        },
        "compiler": {
            "Windows": "winget install Microsoft.VisualStudio.2022.BuildTools",
            "Linux": "sudo apt-get install build-essential",
            "macOS": "xcode-select --install",
        },
        "python_headers": {
            "Windows": "py -3.11 -m pip install --upgrade fullseye",
            "Linux": "sudo apt-get install python3.11-dev",
            "macOS": "brew install python@3.11",
        },
        "pybind11": {
            "Windows": "py -3.11 -m pip install --force-reinstall fullseye",
            "Linux": "python3 -m pip install --force-reinstall fullseye",
            "macOS": "python3 -m pip install --force-reinstall fullseye",
        },
    }
    return commands[component]


def _print_prerequisite_table(missing: list[str], *, stream) -> None:
    """Print every missing native prerequisite with three OS remedies / 不足ごとの三 OS 対処表。"""
    labels = {
        "cmake": "CMake 3.21 or newer",
        "compiler": "a C++ compiler",
        "python_headers": "Python development headers (Python.h)",
        "pybind11": "the pybind11 headers shipped with fullseye",
    }
    for component in missing:
        commands = _platform_commands(component)
        print("MISSING: %s" % labels[component], file=stream)
        print("  Windows: %s" % commands["Windows"], file=stream)
        print("  Linux:   %s" % commands["Linux"], file=stream)
        print("  macOS:   %s" % commands["macOS"], file=stream)


def _missing_prerequisites() -> tuple[list[str], str | None]:
    """Inspect prerequisites without configuring a project / configure 前に必要物を確認する。"""
    missing: list[str] = []
    try:
        import pybind11
        pybind = pybind11.__version__
    except ImportError:
        pybind = None
        missing.append("pybind11")
    cmake = shutil.which("cmake")
    if cmake is None:
        missing.append("cmake")
    compiler_names = ("cl", "g++", "clang++") if os.name == "nt" else ("c++", "g++", "clang++")
    if not any(shutil.which(name) for name in compiler_names):
        missing.append("compiler")
    include = sysconfig.get_path("include")
    if not include or not (Path(include) / "Python.h").is_file():
        missing.append("python_headers")
    print("Python: %s" % sys.executable)
    print("Python headers: %s" % (include or "missing"))
    print("pybind11: %s" % (pybind or "missing"))
    print("CMake: %s" % (cmake or "missing"))
    return missing, cmake


def _doctor() -> int:
    """Check native prerequisites and build/run a C++ consumer probe / 利用側 C++ を組んで確認する。"""
    missing, cmake = _missing_prerequisites()
    if missing:
        _print_prerequisite_table(missing, stream=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory(prefix="fullseye-sdk-doctor-") as temp:
        project = Path(temp)
        (project / "CMakeLists.txt").write_text(
            "cmake_minimum_required(VERSION 3.21)\nproject(fullseye_doctor LANGUAGES CXX)\n"
            "find_package(fullseye CONFIG REQUIRED)\nadd_executable(app main.cpp)\n"
            "target_link_libraries(app PRIVATE fullseye::fullseye)\nfullseye_deploy_runtime(app)\n",
            encoding="utf-8",
        )
        (project / "main.cpp").write_text(
            "#include <fullseye.hpp>\n#include <array>\nint main() {\n"
            "  fullseye::Runtime fs; std::array<double, 4> p{0., .5, 1., .5};\n"
            "  auto image = fullseye::Image::from_buffer(p.data(), 2, 2);\n"
            "  return fs.call(\"gaussian\", image, {{\"a\", .5}}).size() == 1 ? 0 : 1;\n}\n",
            encoding="utf-8",
        )
        configure = [cmake, "-S", str(project), "-B", str(project / "build"),
                     "-Dfullseye_DIR=" + str(_cmake_dir())]
        build = [cmake, "--build", str(project / "build")]
        try:
            subprocess.run(configure, check=True, text=True, timeout=180)
            subprocess.run(build, check=True, text=True, timeout=300)
            executable = project / "build" / ("app.exe" if sys.platform == "win32" else "app")
            subprocess.run([str(executable)], check=True, text=True, timeout=120)
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
            print("MISSING OR BROKEN: the consumer build did not complete: %s" % exc, file=sys.stderr)
            _print_prerequisite_table(["compiler", "python_headers", "pybind11"], stream=sys.stderr)
            return 1
    print("OK: compiler, Python development headers, pybind11, and hello_cpp")
    return 0


def _manifest_path(value: str) -> Path:
    """Accept an executable directory or its manifest / 実行ファイルの directory または manifest を受ける。"""
    target = Path(value).expanduser()
    return target / "fullseye_runtime.json" if target.is_dir() else target


def _relink(value: str) -> int:
    """Write a portable runtime manifest without rebuilding / 再ビルドなしで可搬 manifest を書く。"""
    manifest = _manifest_path(value)
    if manifest.name != "fullseye_runtime.json":
        raise ValueError("relink expects an executable directory or fullseye_runtime.json")
    if not manifest.parent.is_dir():
        raise ValueError("relink target directory does not exist: %s" % manifest.parent)
    payload = {
        "python_executable": str(Path(sys.executable).resolve()),
        "python_home": str(Path(sys.prefix).resolve()),
        "runtime_root": str(package_root().parent),
        "sdk_abi_version": abi_version(),
        "created_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
    }
    temporary = manifest.with_name(manifest.name + ".tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    temporary.replace(manifest)
    print(manifest)
    return 0


def main(argv: list[str] | None = None) -> int:
    """Print one SDK location or diagnose a consumer build / SDK の場所または診断を返す。"""
    argv = sys.argv[1:] if argv is None else argv
    if argv and argv[0] == "relink":
        parser = argparse.ArgumentParser(description="Rewrite a Fullseye runtime manifest without rebuilding")
        parser.add_argument("relink")
        parser.add_argument("target", help="executable directory or fullseye_runtime.json")
        args = parser.parse_args(argv)
        try:
            return _relink(args.target)
        except ValueError as exc:
            parser.error(str(exc))
    parser = argparse.ArgumentParser(description="Fullseye C/C++ source SDK discovery")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--cmakedir", action="store_true", help="print CMake Config directory")
    group.add_argument("--includedir", action="store_true", help="print public header directory")
    group.add_argument("--python", action="store_true", help="print this Python executable")
    group.add_argument("--doctor", action="store_true", help="check and build the C++ consumer probe")
    args = parser.parse_args(argv)
    if args.cmakedir:
        print(_cmake_dir())
    elif args.includedir:
        print(payload_paths()[1])
    elif args.python:
        print(sys.executable)
    else:
        return _doctor()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
