"""Generate the C SDK's typed callable-op JSON and compact help / C SDK 型別 op 一覧を生成。

Usage::

    py -3.11 tools/gen_c_api_ops.py [--check]

The bridge owns the reachability rule, so the public help and the runtime
``fs_find_ops_json`` result cannot drift apart. / 到達可能性の規則は bridge のみが
持ち、公開 help と ``fs_find_ops_json`` の結果がずれないようにする。
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

JSON_PATH = os.path.join(ROOT, "fullseye", "data", "C_API_OPS.json")
HELP_PATH = os.path.join(ROOT, "docs", "C_API_OPS.md")


def _help(data: dict) -> str:
    rows = data["ops"]
    callable_rows = [row for row in rows if row["callable"]]
    blocked = [row for row in rows if not row["callable"]]
    out = [
        "# C SDK callable operators",
        "",
        "Generated by `py -3.11 tools/gen_c_api_ops.py`; do not edit by hand.",
        "",
        "`fs_call_id_n` accepts exactly the declared input and output sorts `image`, "
        "`region`, `color`, `volume`, and `feature`. Other sorts fail closed with "
        "`FS_E_UNSUPPORTED` and the reason below.",
        "",
        "## Summary",
        "",
        "| ledger rows | callable | rejected |",
        "| ---: | ---: | ---: |",
        "| %d | %d | %d |" % (data["n_ops"], data["n_callable"], data["n_rejected"]),
        "",
        "## Callable",
        "",
        "| ID | input | output |",
        "| --- | --- | --- |",
    ]
    out += ["| `%s` | `%s` | `%s` |" % (row["id"], row["in_sort"], row["out_sort"])
            for row in callable_rows]
    out += [
        "",
        "## Rejected by the current ABI",
        "",
        "| ID | input | output | reason |",
        "| --- | --- | --- | --- |",
    ]
    out += ["| `%s` | `%s` | `%s` | %s |" %
            (row["id"], row["in_sort"], row["out_sort"], row["reason"])
            for row in blocked]
    return "\n".join(out) + "\n"


def _write_or_check(path: str, text: str, check: bool) -> bool:
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    if old == text:
        return True
    if check:
        sys.stderr.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True),
                                                   fromfile=path, tofile=path))
        return False
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    from fullseye import c_api_bridge

    data = c_api_bridge.catalog()
    json_text = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    ok = _write_or_check(JSON_PATH, json_text, args.check)
    ok = _write_or_check(HELP_PATH, _help(data), args.check) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
