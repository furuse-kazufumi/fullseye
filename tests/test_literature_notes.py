def _mini_repo(tmp_path, n_notes: int, index_says: int, layer_says: int):
    """壊して確かめるための小さな repo: op ノート ``n_notes`` 枚(うち 1 つは別の族の同名)、索引・guides・SAMPLES は数えない対象。"""
    ops_dir = tmp_path / "docs" / "ops" / "2d" / "smoothing"
    ops_dir.mkdir(parents=True)
    for i in range(n_notes):
        (ops_dir / ("op%d.md" % i)).write_text("---\nop: op%d\ndim: 2d\n---\n\nbody\n" % i, encoding="utf-8")
    other = tmp_path / "docs" / "ops" / "3d" / "x"
    other.mkdir(parents=True)
    (other / "op0.md").write_text("---\nop: op0\ndim: 3d\n---\n\nsame name, other family\n", encoding="utf-8")
    (tmp_path / "docs" / "ops" / "INDEX.md").write_text("# index\n", encoding="utf-8")
    (tmp_path / "docs" / "ops" / "SAMPLES.md").write_text("# samples\n", encoding="utf-8")
    guides = tmp_path / "docs" / "ops" / "2d" / "guides"
    guides.mkdir()
    (guides / "g.md").write_text("# guide\n\nno front matter\n", encoding="utf-8")
    lit = tmp_path / "docs" / "literature"
    lit.mkdir()
    (lit / "INDEX.md").write_text("Fullseye の RAG(`docs/ops` の op ノート {:,} 本)は土台。\n".format(index_says), encoding="utf-8")
    (lit / "mech_design.md").write_text("<!-- generated by tools/gen_literature_notes.py from the RAD corpus x_corpus_v2 (built 2026-01-01) -->\n"
                                  "生成時に出荷ノート {:,} 本の一覧と突き合わせ。\n".format(layer_says), encoding="utf-8")
    return tmp_path


def test_count_gate_break_probe_stale_index_and_layer(tmp_path):
    g = _gen()
    repo = _mini_repo(tmp_path, n_notes=5, index_says=6, layer_says=5)       # 枚数 6(同名を別々に数える)/ 名前 5
    assert g.count_op_notes(str(repo)) == (6, 5), "INDEX・SAMPLES・guides を数えたか、同名の別の族を落とした"
    assert g.stated_count_problems(str(repo)) == []
    # 1 枚足す(= op を足した)だけで赤くなる
    (repo / "docs" / "ops" / "2d" / "smoothing" / "new.md").write_text("---\nop: new\n---\n", encoding="utf-8")
    probs = g.stated_count_problems(str(repo))
    assert len(probs) == 2 and "INDEX.md" in probs[0] and "mech_design.md" in probs[1], probs
    # 打ち直すと緑に戻り、2 回目は何も書かない
    changed = g.restate_counts(str(repo))
    assert sorted(os.path.basename(p) for p in changed) == ["INDEX.md", "mech_design.md"]
    assert g.stated_count_problems(str(repo)) == [] and g.restate_counts(str(repo)) == []
    assert "7 本" in (repo / "docs" / "literature" / "INDEX.md").read_text(encoding="utf-8")
    assert "6 本" in (repo / "docs" / "literature" / "mech_design.md").read_text(encoding="utf-8")


