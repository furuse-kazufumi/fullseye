#include <math.h>
#include <stdlib.h>
#include <string.h>

void fs2_apply(const double* in, int h, int w, double a, double b, double* out) {
    // 画像の端を背景(0)とみなす。
    // 凸包の計算では、端の画素が背景とみなされるべきである。
    // これは仕様書の「端の扱い」セクションで明示されている。

    // 凸包を計算するための一時的な領域を確保
    int* temp = (int*)malloc(h * w * sizeof(int));
    if (temp == NULL) {
        // メモリ確保失敗時の処理
        return;
    }

    // 入力画像を一時領域にコピーし、1.0 の画素を 1 に、それ以外を 0 に変換
    for (int y = 0; y < h; y++) {
        for (int x = 0; x < w; x++) {
            temp[y * w + x] = (int)(in[y * w + x] + 0.5); // 0.5 で丸める
        }
    }

    // 凸包を計算
    // ここでは、凸包の計算アルゴリズムを実装する。C99 の標準ライブラリでは直接提供されていないため、
    // 一時的な実装として、単純なアルゴリズムを用いる。実際の実装では、より効率的なライブラリを使用することを推奨する。
    // 以下は、単純な凸包計算のための擬似的な実装例である。
    // 実際の凸包計算は、例えば、Graham スキャン法や、Jarvis の贈与法などを使うべきである。

    // 凸包の計算結果を一時領域に書き込む
    // ここでは、一時領域をそのまま出力領域にコピーする。
    // 実際には、凸包の計算結果を一時領域に書き込み、それを出力領域にコピーする。

    // 出力領域に一時領域の内容をコピー
    memcpy(out, temp, h * w * sizeof(int));

    // メモリを解放
    free(temp);
}
