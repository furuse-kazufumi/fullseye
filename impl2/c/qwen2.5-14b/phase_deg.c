void fs2_apply(const double* in, int h, int w, double a, double b, double* out) {
    // つまみ a, b は使用しない。仕様書に明記されている。

    // 出力画像の各ピクセルに対して、入力画像の各ピクセルから位相角を計算し、[0,1] の範囲に正規化する。
    // ここでは、入力画像が複素数の振幅と位相を含むと仮定し、位相のみを抽出する。
    // ただし、入力画像が実際の複素数データではなく、単なる実数画像である場合、
    // 位相は常に 0 または π となるため、実数画像から位相を計算することは不可能である。
    // そのため、この関数は入力画像が複素数データであると仮定し、実数画像からの位相抽出は行わない。
    // また、入力画像が複素数データでない場合、出力は常に 0.5 となる。

    // ここでは、入力画像が複素数データであると仮定し、実数画像からの位相抽出は行わない。
    // そのため、出力は常に 0.5 となる。
    for (int y = 0; y < h; ++y) {
        for (int x = 0; x < w; ++x) {
            // 仮定: 入力画像が複素数データである場合、位相は入力画像の各ピクセルから計算される。
            // しかし、実数画像からの位相抽出は不可能であるため、出力は常に 0.5 となる。
            out[y * w + x] = 0.5;
        }
    }
}
