void fs2_apply(const double* in, int h, int w, double a, double b, double* out) {
    // つまみ a, b は未使用。この関数では無視する。

    // まず、入力画像の高さと幅を元に出力画像を初期化する。
    // 全ての画素を 0 に初期化する。
    for (int y = 0; y < h; ++y) {
        for (int x = 0; x < w; ++x) {
            out[y * w + x] = 0.0;
        }
    }

    // 連結成分ラベル付けを行う。ラベル付けの結果は out に直接書き込む。
    // ここでは、ラベル付けの結果を 1 に書き込むことで、全ての 1 の集合を表す。
    // 連結成分ラベル付けは、前景画素 (in[y*w + x] > 0.5) を持つ全ての画素を 1 に設定する。
    for (int y = 0; y < h; ++y) {
        for (int x = 0; x < w; ++x) {
            if (in[y * w + x] > 0.5) {
                out[y * w + x] = 1.0;
            }
        }
    }

    // 連結成分ラベル付けの結果を 1 に設定することで、全ての 1 の集合を表す。
    // これは、入力を 0/1 に正規化した結果と同じになる。
}
